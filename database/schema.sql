CREATE TABLE IF NOT EXISTS investigations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR NOT NULL,
    status VARCHAR(10) NOT NULL,
    warnings CLOB NOT NULL
);

CREATE TABLE IF NOT EXISTS incidents (
    case_id INTEGER REFERENCES investigations(id) ON DELETE CASCADE,
    incident_no INTEGER NOT NULL,
    user_name VARCHAR NOT NULL,
    host_name VARCHAR NOT NULL,
    start_time VARCHAR NOT NULL,
    end_time VARCHAR NOT NULL,
    priority VARCHAR(10) NOT NULL,
    PRIMARY KEY (case_id, incident_no)
);

CREATE TABLE IF NOT EXISTS log_events (
    case_id INTEGER REFERENCES investigations(id) ON DELETE CASCADE,
    position_no INTEGER NOT NULL,
    event_time VARCHAR NOT NULL,
    user_name VARCHAR NOT NULL,
    host_name VARCHAR NOT NULL,
    action_name VARCHAR NOT NULL,
    detail VARCHAR NOT NULL,
    source_file VARCHAR NOT NULL,
    source_line INTEGER NOT NULL,
    finding VARCHAR NOT NULL,
    incident_no INTEGER,
    PRIMARY KEY (case_id, position_no),
    FOREIGN KEY (case_id, incident_no) REFERENCES incidents(case_id, incident_no) ON DELETE CASCADE
);
